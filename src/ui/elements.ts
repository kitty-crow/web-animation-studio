function required(id: string): HTMLElement { const value=document.getElementById(id); if(!value)throw Error('Missing #'+id); return value; }
function element<T extends HTMLElement>(id: string, tag: string): T {
 const value=required(id);
 if(value.tagName.toLowerCase()!==tag)throw Error('Expected '+tag+' #'+id);
 return value as T;
}
